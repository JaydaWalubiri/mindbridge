from django.core.management.base import BaseCommand
from care.models import Participant

DEMO_SEEDED_CODES = {"MB-1001", "MB-1002", "MB-1003", "MB-1004", "MB-1005", "MB-1006"}


class Command(BaseCommand):
    help = "Delete simulated test participants generated by the WhatsApp preview simulator."

    def add_arguments(self, parser):
        parser.add_argument(
            "--all",
            action="store_true",
            help="Delete all simulated participants (including seeded demo participants MB-1001 to MB-1006).",
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Show participants that would be deleted without deleting them.",
        )

    def handle(self, *args, **options):
        query = Participant.objects.filter(is_simulated=True)
        if not options["all"]:
            # Only remove ephemeral chat simulator records
            query = query.filter(code__startswith="MB-CHAT-")

        count = query.count()
        if count == 0:
            self.stdout.write(self.style.SUCCESS("No matching test participants found."))
            return

        self.stdout.write(f"Found {count} test participant(s):")
        for p in query:
            self.stdout.write(f"  - {p.code} ({p.display_name}, age: {p.age or 'N/A'}, area: {p.area or 'None'})")

        if options["dry_run"]:
            self.stdout.write(self.style.WARNING("Dry-run mode: no records were deleted."))
            return

        deleted_count, _ = query.delete()
        self.stdout.write(self.style.SUCCESS(f"Successfully deleted {count} test participant(s) and their cascading records."))
